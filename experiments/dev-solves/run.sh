#!/usr/bin/env bash
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
gradle=${GRADLE:-$repo/gradlew}
solved=${SOLVED:-$here/certificates}
out=${OUT_DIR:-$here/../results/dev-solves/runs/$(date -u +%Y%m%dT%H%M%SZ)}
committed=$repo/bench/data/solves/dev.json
after_dir=$here/certificates-after
check=0
after=0

usage() {
    echo "usage: run.sh [--check] [--after|--limits|--x1|--p8] [--solved DIR[,DIR...]] [--out DIR]"
    echo "env: GRADLE (launcher and flags, default repo gradlew), SOLVED (case directories, default experiments/dev-solves/certificates), OUT_DIR"
}

while [ $# -gt 0 ]; do
    case $1 in
    --check) check=1 ;;
    --after) after=1; committed=$repo/bench/data/solves/dev-after.json ;;
    --limits) solved=$here/certificates-limits; committed=$repo/bench/data/solves/dev-limits.json ;;
    --x1) solved=$here/certificates-x1; committed=$repo/bench/data/solves/dev-x1-a.json ;;
    --p8) solved=$here/certificates-p8; committed=$repo/bench/data/solves/dev-p8.json ;;
    --solved) solved=$2; shift ;;
    --out) out=$2; shift ;;
    -h | --help) usage; exit 0 ;;
    *) usage >&2; exit 64 ;;
    esac
    shift
done

fail() {
    echo "$1" >&2
    exit 1
}

check_after() {
    local c
    [ -d "$after_dir" ] || fail "no $after_dir"
    for c in "$after_dir"/*/; do
        [ -d "$here/certificates/$(basename "$c")" ] || fail "$c replaces no case in certificates"
        [ -f "${c}certificate.json" ] || fail "no certificate.json in $c"
    done
    echo "$(ls "$after_dir" | wc -l | tr -d ' ') cases replaced by $after_dir"
}

merge_after() {
    local c
    mkdir -p "$1"
    for c in "$here/certificates"/*/; do
        [ -d "$after_dir/$(basename "$c")" ] || cp -R "$c" "$1/"
    done
    cp -R "$after_dir"/*/ "$1/"
}

check_inputs() {
    local d n total=0
    [ $after = 0 ] || check_after
    for f in bench/data/scenarios.json bench/data/split.json bench/data/calibration/evaluation.json bench/data/solves/dev.json bench/runner/run-solve.sh bench/runner/prepull.sh; do
        [ -f "$repo/$f" ] || fail "missing $f"
    done
    for d in ${solved//,/ }; do
        [ -d "$d" ] || fail "no case directory $d"
        n=0
        for c in "$d"/*/; do
            [ -f "${c}certificate.json" ] || fail "no certificate.json in $c"
            n=$((n + 1))
        done
        echo "$d: $n cases"
        total=$((total + n))
    done
    grep -q '"scenarios":'"$total"',' "$committed" || fail "dev.json does not hold $total scenarios"
    echo "$total cases; would run: solves --root <scratch bench> --solved $solved, then cmp with ${committed#$repo/}"
}

if [ $check = 1 ]; then
    check_inputs
    exit 0
fi

check_inputs
[ ! -e "$out" ] || fail "$out exists; pick a new --out"
if [ $after = 1 ]; then
    merge_after "$out/merged"
    solved=$out/merged
fi
mkdir -p "$out/bench/data/calibration"
for f in scenarios.json split.json; do cp "$repo/bench/data/$f" "$out/bench/data/$f"; done
cp "$repo/bench/data/calibration/evaluation.json" "$out/bench/data/calibration/evaluation.json"

$gradle -p "$repo" --console=plain -q :bench:jvmRun --args="solves --root $out/bench --solved $solved" | tee "$out/report.txt"

if cmp -s "$out/bench/data/solves/dev.json" "$committed"; then
    echo "$(basename "$committed") regenerated byte for byte"
else
    cp "$out/bench/data/solves/dev.json" "$out/dev.json"
    fail "dev.json differs from $committed; the new one is $out/dev.json"
fi

echo "paisley: copy bench/ and experiments/dev-solves/ into a drift-cisim:3 container (capped at 10 GB and 8 CPUs) and run experiments/dev-solves/run.sh there; the run needs no Docker of its own"
