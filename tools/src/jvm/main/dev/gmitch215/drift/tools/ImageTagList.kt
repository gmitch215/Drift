package dev.gmitch215.drift.tools

import java.net.URI
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import java.nio.file.Path
import java.time.Duration
import kotlin.io.path.writeText

/**
 * Writes `ImageTags.kt` in `core`: the tags of the official Docker Hub repositories that
 * `ImageTable` composes, so it can pick an existing tag offline. Run by hand, never in `build`.
 */
object ImageTagList {
    private const val CODENAMES = "(?:buster|bullseye|bookworm|trixie)"
    private const val ALPINE = "alpine\\d+\\.\\d+"
    private const val VERSION = "\\d+\\.\\d+\\.\\d+"
    private const val LINE = 80

    val shapes: Map<String, List<Regex>> = linkedMapOf(
        "eclipse-temurin" to listOf(
            Regex("^\\d+-jdk(?:-(?:focal|jammy|noble)|-alpine(?:-\\d+\\.\\d+)?)?$"),
        ),
        "gcc" to listOf(Regex("^\\d+\\.\\d+(?:\\.\\d+)?$")),
        "golang" to listOf(
            Regex("^\\d+\\.\\d+(?:\\.\\d+)?-(?:$CODENAMES|$ALPINE)$"),
        ),
        "node" to listOf(Regex("^$VERSION-(?:$CODENAMES-slim|$ALPINE)$")),
        "php" to listOf(Regex("^$VERSION-(?:cli|zts)-(?:$CODENAMES|$ALPINE)$")),
        "python" to listOf(Regex("^$VERSION-(?:slim-$CODENAMES|$ALPINE)$")),
        "r-base" to listOf(Regex("^$VERSION$")),
        "ruby" to listOf(Regex("^$VERSION-(?:slim-$CODENAMES|$ALPINE)$")),
        "elixir" to listOf(Regex("^$VERSION(?:-otp-\\d+)?$")),
        "rust" to listOf(Regex("^$VERSION-(?:slim-$CODENAMES|$ALPINE)$")),
    )

    private val split = Regex("^(\\d+(?:\\.\\d+)*)(.*)$")

    /** Tags of [repository] that [shapes] keep, grouped by the text after the version. */
    fun group(repository: String, tags: List<String>): Map<String, List<String>> {
        val keep = shapes.getValue(repository)
        return tags.filter { t -> keep.any { it.matches(t) } }
            .map { split.matchEntire(it)!!.destructured }
            .groupBy({ it.component2() }, { it.component1() })
            .toSortedMap()
            .mapValues { (_, versions) -> versions.distinct().sortedWith(::compareVersions) }
    }

    fun compareVersions(a: String, b: String): Int {
        val x = a.split('.').map { it.toInt() }
        val y = b.split('.').map { it.toInt() }
        for (i in 0 until maxOf(x.size, y.size)) {
            val c = x.getOrElse(i) { -1 }.compareTo(y.getOrElse(i) { -1 })
            if (c != 0) return c
        }
        return 0
    }

    fun render(tags: Map<String, List<String>>): String = buildString {
        append("package dev.gmitch215.drift.lab\n\n")
        append("/** Generated by `./gradlew :tools:imageTags`; edit nothing by hand. */\n")
        append("internal object ImageTags {\n")
        append("    val repositories: Map<String, Map<String, Set<String>>> = mapOf(\n")
        for ((repository, all) in tags.toSortedMap()) {
            append("        \"$repository\" to mapOf(\n")
            for ((rest, versions) in group(repository, all)) {
                append("            \"$rest\" to versions(\n")
                append("                \"\"\"\n")
                for (line in wrap(versions)) append("                $line\n")
                append("                \"\"\",\n")
                append("            ),\n")
            }
            append("        ),\n")
        }
        append("    )\n\n")
        append("    private fun versions(text: String): Set<String> =\n")
        append("        text.split(' ', '\\n').filter { it.isNotEmpty() }.toSet()\n")
        append("}\n")
    }

    private fun wrap(words: List<String>): List<String> {
        val lines = mutableListOf<String>()
        var current = StringBuilder()
        for (w in words) {
            if (current.isNotEmpty() && current.length + 1 + w.length > LINE) {
                lines += current.toString()
                current = StringBuilder()
            }
            if (current.isNotEmpty()) current.append(' ')
            current.append(w)
        }
        if (current.isNotEmpty()) lines += current.toString()
        return lines
    }

    private val client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(20)).build()

    private fun get(url: String, token: String? = null): String {
        val request = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(120))
            .apply { if (token != null) header("Authorization", "Bearer $token") }
            .GET().build()
        val response = client.send(request, HttpResponse.BodyHandlers.ofString())
        check(response.statusCode() == 200) { "$url answered ${response.statusCode()}" }
        return response.body()
    }

    private fun fetch(repository: String): List<String> {
        val auth = "https://auth.docker.io/token?service=registry.docker.io" +
            "&scope=repository:library/$repository:pull"
        val token = Regex("\"token\":\"([^\"]+)\"").find(get(auth))!!.groupValues[1]
        val list = get(
            "https://registry-1.docker.io/v2/library/$repository/tags/list?n=100000",
            token,
        )
        return Regex("\"([^\"]+)\"").findAll(list.substringAfter("\"tags\":["))
            .map { it.groupValues[1] }.toList()
    }

    fun write(out: Path) {
        val tags = shapes.keys.associateWith { fetch(it) }
        out.writeText(render(tags))
        for ((repository, all) in tags) {
            println("$repository ${group(repository, all).values.sumOf { it.size }} tags")
        }
    }
}
